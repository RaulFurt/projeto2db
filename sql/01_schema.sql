-- =====================================================================
-- Controle de Patrimônio Corporativo — Iteração 2
-- 01_schema.sql : criação das tabelas, restrições, índices, views e triggers
-- SGBD: PostgreSQL 14+
-- =====================================================================

DROP VIEW     IF EXISTS vw_equipamento CASCADE;
DROP VIEW     IF EXISTS vw_posse_atual CASCADE;
DROP TABLE    IF EXISTS acautelamento, manutencao, equipamento, funcionario,
                        fornecedor_telefone, fornecedor, setor, categoria CASCADE;
DROP FUNCTION IF EXISTS fn_acautelamento_valida() CASCADE;
DROP FUNCTION IF EXISTS fn_acautelamento_retirada() CASCADE;
DROP FUNCTION IF EXISTS fn_acautelamento_devolucao() CASCADE;

-- ---------------------------------------------------------------------
-- CATEGORIA
-- [Iteração 2] novo atributo vida_util_meses (base para depreciação)
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id_categoria    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(60)  NOT NULL UNIQUE,
    descricao       VARCHAR(255),
    vida_util_meses INTEGER      NOT NULL CHECK (vida_util_meses > 0)
);

-- ---------------------------------------------------------------------
-- SETOR
-- Atributo composto localizacao(bloco, sala) mapeado em duas colunas
-- ---------------------------------------------------------------------
CREATE TABLE setor (
    id_setor INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(80) NOT NULL,
    bloco    VARCHAR(30) NOT NULL,
    sala     VARCHAR(10) NOT NULL,
    UNIQUE (bloco, sala)
);

-- ---------------------------------------------------------------------
-- FORNECEDOR
-- ---------------------------------------------------------------------
CREATE TABLE fornecedor (
    cnpj         CHAR(14)     PRIMARY KEY CHECK (cnpj ~ '^[0-9]{14}$'),
    razao_social VARCHAR(120) NOT NULL,
    email        VARCHAR(120)
);

-- Atributo multivalorado telefone -> tabela própria
-- [Iteração 2] cada telefone ganha um tipo (Vendas / Suporte / Geral)
CREATE TABLE fornecedor_telefone (
    cnpj     CHAR(14)    NOT NULL REFERENCES fornecedor (cnpj)
                         ON UPDATE CASCADE ON DELETE CASCADE,
    telefone VARCHAR(20) NOT NULL,
    tipo     VARCHAR(10) NOT NULL DEFAULT 'Geral'
                         CHECK (tipo IN ('Vendas', 'Suporte', 'Geral')),
    PRIMARY KEY (cnpj, telefone)
);

-- ---------------------------------------------------------------------
-- FUNCIONARIO
-- [Iteração 2] novo relacionamento "lotado em" (N:1 com SETOR) e flag ativo
-- ---------------------------------------------------------------------
CREATE TABLE funcionario (
    matricula INTEGER      PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL,
    cargo     VARCHAR(60)  NOT NULL,
    id_setor  INTEGER      NOT NULL REFERENCES setor (id_setor),
    ativo     BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- EQUIPAMENTO
-- Relacionamentos 1:N classifica / alocado em / fornece viram FKs NOT NULL
-- (participação total do lado N). tempo_uso é derivado -> calculado na view.
-- [Iteração 2] status com domínio fixo, numero_serie único,
--              novo atributo data_fim_garantia
-- ---------------------------------------------------------------------
CREATE TABLE equipamento (
    patrimonio        INTEGER       PRIMARY KEY,
    nome              VARCHAR(80)   NOT NULL,
    marca             VARCHAR(40)   NOT NULL,
    modelo            VARCHAR(60),
    numero_serie      VARCHAR(40)   NOT NULL UNIQUE,
    data_aquisicao    DATE          NOT NULL,
    valor             NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
    status            VARCHAR(15)   NOT NULL DEFAULT 'Disponivel'
                      CHECK (status IN ('Disponivel', 'Em uso', 'Em manutencao', 'Descartado')),
    data_fim_garantia DATE,
    id_categoria      INTEGER       NOT NULL REFERENCES categoria (id_categoria),
    id_setor          INTEGER       NOT NULL REFERENCES setor (id_setor),
    cnpj_fornecedor   CHAR(14)      NOT NULL REFERENCES fornecedor (cnpj) ON UPDATE CASCADE,
    CHECK (data_fim_garantia IS NULL OR data_fim_garantia >= data_aquisicao)
);

CREATE INDEX idx_equipamento_categoria ON equipamento (id_categoria);
CREATE INDEX idx_equipamento_setor     ON equipamento (id_setor);
CREATE INDEX idx_equipamento_status    ON equipamento (status);

-- ---------------------------------------------------------------------
-- MANUTENCAO (entidade fraca)
-- PK = patrimonio (dono) + seq (chave parcial). ON DELETE CASCADE.
-- [Iteração 2] novo atributo tipo (Preventiva / Corretiva)
-- ---------------------------------------------------------------------
CREATE TABLE manutencao (
    patrimonio INTEGER       NOT NULL REFERENCES equipamento (patrimonio)
                             ON DELETE CASCADE,
    seq        INTEGER       NOT NULL CHECK (seq > 0),
    data       DATE          NOT NULL,
    tipo       VARCHAR(10)   NOT NULL CHECK (tipo IN ('Preventiva', 'Corretiva')),
    descricao  VARCHAR(255)  NOT NULL,
    custo      NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (custo >= 0),
    PRIMARY KEY (patrimonio, seq)
);

-- ---------------------------------------------------------------------
-- ACAUTELAMENTO
-- [Iteração 2] o relacionamento N:M "utiliza" virou entidade associativa
-- com identificador próprio, permitindo que o MESMO funcionário retire o
-- MESMO equipamento várias vezes (impossível com PK (matricula, patrimonio)).
-- data_devolucao NULL = equipamento ainda está com o funcionário.
-- ---------------------------------------------------------------------
CREATE TABLE acautelamento (
    id_acautelamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patrimonio       INTEGER NOT NULL REFERENCES equipamento (patrimonio) ON DELETE CASCADE,
    matricula        INTEGER NOT NULL REFERENCES funcionario (matricula),
    data_retirada    DATE    NOT NULL,
    data_devolucao   DATE,
    CHECK (data_devolucao IS NULL OR data_devolucao >= data_retirada)
);

CREATE INDEX idx_acautelamento_matricula ON acautelamento (matricula);

-- Regra de negócio: um equipamento só pode ter UM acautelamento em aberto
CREATE UNIQUE INDEX ux_acautelamento_aberto
    ON acautelamento (patrimonio) WHERE data_devolucao IS NULL;

-- ---------------------------------------------------------------------
-- TRIGGERS — mantêm o status do equipamento coerente com o acautelamento
-- ---------------------------------------------------------------------

-- Só pode retirar equipamento 'Disponivel'
CREATE FUNCTION fn_acautelamento_valida() RETURNS trigger AS $$
BEGIN
    IF (SELECT status FROM equipamento WHERE patrimonio = NEW.patrimonio) <> 'Disponivel' THEN
        RAISE EXCEPTION 'Equipamento % indisponivel para acautelamento', NEW.patrimonio;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_acautelamento_valida
BEFORE INSERT ON acautelamento
FOR EACH ROW WHEN (NEW.data_devolucao IS NULL)
EXECUTE FUNCTION fn_acautelamento_valida();

-- Retirada -> 'Em uso'
CREATE FUNCTION fn_acautelamento_retirada() RETURNS trigger AS $$
BEGIN
    UPDATE equipamento SET status = 'Em uso' WHERE patrimonio = NEW.patrimonio;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_acautelamento_retirada
AFTER INSERT ON acautelamento
FOR EACH ROW WHEN (NEW.data_devolucao IS NULL)
EXECUTE FUNCTION fn_acautelamento_retirada();

-- Devolução -> 'Disponivel'
CREATE FUNCTION fn_acautelamento_devolucao() RETURNS trigger AS $$
BEGIN
    UPDATE equipamento SET status = 'Disponivel'
     WHERE patrimonio = NEW.patrimonio AND status = 'Em uso';
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_acautelamento_devolucao
AFTER UPDATE OF data_devolucao ON acautelamento
FOR EACH ROW WHEN (OLD.data_devolucao IS NULL AND NEW.data_devolucao IS NOT NULL)
EXECUTE FUNCTION fn_acautelamento_devolucao();

-- ---------------------------------------------------------------------
-- VIEWS
-- ---------------------------------------------------------------------

-- Atributo derivado tempo_uso + indicadores de depreciação e garantia.
-- Depreciação linear: valor_atual = valor * (1 - meses_uso / vida_util), mínimo 0.
CREATE VIEW vw_equipamento AS
SELECT e.patrimonio,
       e.nome,
       e.marca,
       e.modelo,
       e.numero_serie,
       e.status,
       e.data_aquisicao,
       e.valor,
       c.nome         AS categoria,
       s.nome         AS setor,
       s.bloco,
       s.sala,
       f.razao_social AS fornecedor,
       e.data_fim_garantia,
       (EXTRACT(YEAR  FROM age(CURRENT_DATE, e.data_aquisicao)) * 12
      + EXTRACT(MONTH FROM age(CURRENT_DATE, e.data_aquisicao)))::INTEGER AS tempo_uso_meses,
       c.vida_util_meses,
       ROUND(GREATEST(0, e.valor * (1 - (CURRENT_DATE - e.data_aquisicao) / 30.4375
                                         / c.vida_util_meses)), 2)     AS valor_atual,
       COALESCE(e.data_fim_garantia >= CURRENT_DATE, FALSE)            AS em_garantia,
       (SELECT COALESCE(SUM(m.custo), 0) FROM manutencao m
         WHERE m.patrimonio = e.patrimonio)                            AS custo_manutencao
  FROM equipamento e
  JOIN categoria  c ON c.id_categoria = e.id_categoria
  JOIN setor      s ON s.id_setor     = e.id_setor
  JOIN fornecedor f ON f.cnpj         = e.cnpj_fornecedor;

-- Quem está com qual equipamento agora (acautelamentos em aberto)
CREATE VIEW vw_posse_atual AS
SELECT a.id_acautelamento,
       e.patrimonio,
       e.nome   AS equipamento,
       fu.matricula,
       fu.nome  AS funcionario,
       fu.cargo,
       a.data_retirada,
       CURRENT_DATE - a.data_retirada AS dias_em_posse
  FROM acautelamento a
  JOIN equipamento e  ON e.patrimonio = a.patrimonio
  JOIN funcionario fu ON fu.matricula = a.matricula
 WHERE a.data_devolucao IS NULL;
